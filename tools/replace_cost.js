const changed = [];
for (const file of walk(root)) {
  let text = fs.readFileSync(file, 'utf8');
  const orig = text;
  for (const [oldS, newS] of replacements) {
    text = text.split(oldS).join(newS);
  }
  if (text !== orig) {
    fs.writeFileSync(file, text, 'utf8');
    changed.push(path.relative(root, file));
  }
}

